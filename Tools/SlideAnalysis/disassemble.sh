#!/usr/bin/env bash
# Offline inspection only. Does not install or modify PSP firmware.
set -euo pipefail

analysis_out="${1:-slide-analysis}"
mkdir -p "$analysis_out"
analysis_out="$(cd "$analysis_out" && pwd)"
analysis_work="$(mktemp -d)"
trap 'rm -rf "$analysis_work"' EXIT

git clone --quiet https://github.com/pspdev/prxtool.git "$analysis_work/prxtool"
git -C "$analysis_work/prxtool" checkout --quiet 08849d87fa8692f2ba29238ec1710f2706e3e021
(
  cd "$analysis_work/prxtool"
  ./bootstrap
  ./configure CXXFLAGS="-O2 -std=gnu++11 -fpermissive"
  make -j2
) > "$analysis_out/tool-build.log" 2>&1 || {
  cat "$analysis_out/tool-build.log"
  exit 1
}

curl --fail --location --retry 3 --max-time 120 \
  https://github.com/NightStar3/zerovsh-patcher/releases/download/0.4/ZeroVSH_Patcher_v0.4.BIN.zip \
  -o "$analysis_work/source.zip"

python3 - "$analysis_work" "$analysis_out" <<'PY'
import sys, zipfile, hashlib, json
from pathlib import Path
work, out = map(Path, sys.argv[1:])
expected = {
    "slide_plugin_660.prx": "8cae94bf24e351c8d3e36959c0e95200c109040f55e9ab5586b243236994a10c",
    "slide_plugin_660.rco": "b8b2ca01e519799a6ce17bd40ea30e22a1eca3c68e91f64afac178dc9d8b57e8",
}
manifest = {
    "source": "NightStar3/zerovsh-patcher release 0.4",
    "firmware_note": "6.60-labeled modules packaged in a 6.61-supporting release; not verified as an exact 6.61 dump.",
    "prxtool_commit": "08849d87fa8692f2ba29238ec1710f2706e3e021",
    "files": [],
}
with zipfile.ZipFile(work / "source.zip") as archive:
    for name, sha in expected.items():
        matches = [n for n in archive.namelist() if n.endswith("/" + name)]
        if len(matches) != 1:
            raise RuntimeError("Missing or ambiguous archive member: " + name)
        data = archive.read(matches[0])
        if hashlib.sha256(data).hexdigest() != sha:
            raise RuntimeError("Source hash mismatch: " + name)
        if name.endswith(".prx") and data[:4] != b"\x7fELF":
            raise RuntimeError("Expected decrypted ELF")
        (work / name).write_bytes(data)
        manifest["files"].append({"name": name, "bytes": len(data), "sha256": sha})
(out / "provenance.json").write_text(json.dumps(manifest, indent=2) + "\n")
PY

analysis_input="$analysis_work/slide_plugin_660.prx"
analysis_tool="$analysis_work/prxtool/prxtool"
readelf -h -l -S "$analysis_input" > "$analysis_out/elf-layout.txt"
"$analysis_tool" -m "$analysis_input" > "$analysis_out/module-info.txt" 2> "$analysis_out/module-info.log"
"$analysis_tool" -f "$analysis_input" > "$analysis_out/imports-exports.txt" 2> "$analysis_out/imports-exports.log"
"$analysis_tool" -w -o "$analysis_out/slide_plugin_660.asm" "$analysis_input" 2> "$analysis_out/disassembly.log"
"$analysis_tool" -x -o "$analysis_out/module.xml" "$analysis_input" 2> "$analysis_out/xml.log"
strings -a -t x "$analysis_input" > "$analysis_out/strings.txt"
strings -a -t x "$analysis_work/slide_plugin_660.rco" > "$analysis_out/rco-strings.txt"

python3 - "$analysis_out" <<'PY'
import sys
from pathlib import Path
out = Path(sys.argv[1])
assembly = (out / "slide_plugin_660.asm").read_text(errors="replace")
if len(assembly) < 1000:
    raise RuntimeError("Disassembly unexpectedly empty")
note = """# PSP Go slide module analysis
Generated by the PSP/Allegrex PRXTool, not the ARM-targeted fork.
The source is labeled 6.60, bundled with ZeroVSH 0.4 which supports 6.61.
No exact 6.61 match or hardware compatibility is claimed.
Addresses are module-relative; relocation records and NIDs require interpretation.
An assembly listing is not recovered original C source.
Input-related string matches are candidates, not verified L/R handlers.
Sony firmware binaries are not included in these outputs.
"""
(out / "README.md").write_text(note)
print("ASSEMBLY:", len(assembly.splitlines()), "lines")
for name in ("module-info.txt", "module-info.log", "imports-exports.txt", "imports-exports.log"):
    print("\n--- " + name + " ---")
    print("\n".join((out / name).read_text(errors="replace").splitlines()[:160]))
print("\n--- First 50 assembly lines ---")
print("\n".join(assembly.splitlines()[:50]))
PY
