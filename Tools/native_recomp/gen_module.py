#!/usr/bin/env python3
"""
Turns N64Recomp output into a DaedalusX64 native code module.

usage: gen_module.py <module name> <N64Recomp .c file> <ELF> <ROM .z64> <out .c> [functions...]

- Puts NATIVE_COUNT_OP() after every guest instruction, so the guest cycle
  counter advances exactly as in the interpreter.
- Rewrites stores ("MEM_W(o, r) = v;") into NATIVE_SW(o, r, v) so they go
  through Daedalus (see Source/Native/recomp.h).
- For every function the code calls that was not recompiled, adds a bridge
  that runs it in Daedalus (native_call_guest).
- Writes the module table: ROM CRCs from the ROM header, and per function its
  address, size and a checksum of its guest code taken from the ELF.
"""
import re, struct, subprocess, sys

name, csrc, elf, rom, out = sys.argv[1:6]
wanted = set(sys.argv[6:])
# Daedalus's ROM id reads the header CRCs as little endian words (same as roms.ini)
rom_crc1, rom_crc2 = struct.unpack('<II', open(rom, 'rb').read()[0x10:0x18])

# ELF symbols and code bytes (big endian MIPS)
syms = {}
for line in subprocess.check_output(['mips-linux-gnu-nm', '-S', elf], text=True).splitlines():
    p = line.split()
    if len(p) == 4 and p[2] in 'Tt':
        syms[p[3]] = (int(p[0], 16), int(p[1], 16))
# Section table, to read each function's guest code from the ELF file
elf_bytes = open(elf, 'rb').read()
sections = []
for line in subprocess.check_output(['mips-linux-gnu-readelf', '-S', '-W', elf], text=True).splitlines():
    p = line.replace('[ ', '[').split()
    if len(p) > 6 and p[0].startswith('[') and p[2] == 'PROGBITS':
        sections.append((int(p[3], 16), int(p[4], 16), int(p[5], 16)))

def code_hash(vram, size):
    addr, off, sec_size = next(s for s in sections if s[0] <= vram < s[0] + s[2])
    base = off + (vram - addr)
    h = 2166136261
    for i in range(size // 4):
        w = struct.unpack('>I', elf_bytes[base + 4 * i: base + 4 * i + 4])[0]
        h = ((h ^ w) * 16777619) & 0xFFFFFFFF
    return h

src = open(csrc).read().splitlines()
defined = []
body = []
for line in src:
    m = re.match(r'RECOMP_FUNC void (\w+)\(uint8_t\* rdram, recomp_context\* ctx\) \{', line)
    if m:
        defined.append(m.group(1))
    if line.startswith('#include'):
        continue
    # stores
    m = re.match(r'^(\s*)MEM_(W|H|B)\((.*)$', line)
    if m:
        rest = m.group(3)
        depth, i = 1, 0
        while depth:
            depth += {'(': 1, ')': -1}.get(rest[i], 0)
            i += 1
        args, tail = rest[:i - 1], rest[i:]
        if tail.startswith(' = ') and tail.endswith(';'):
            line = f'{m.group(1)}NATIVE_S{m.group(2)}({args}, {tail[3:-1]});'
    body.append(line)
    m = re.match(r'^(\s*)// 0x([0-9A-Fa-f]+):\s+(\w+)', line)
    if m:
        indent = m.group(1)
        body.append(f'{indent}NATIVE_COUNT_OP();')
        # jal/jalr write the return address before the delay slot, as on the
        # real CPU (N64Recomp leaves ra alone). Guest code called back from
        # native code then sees the same ra, and saves the same value on its
        # stack, as in the dynarec.
        if m.group(3) in ('jal', 'jalr', 'bal', 'bgezal', 'bltzal'):
            ret = (int(m.group(2), 16) + 8) & 0xFFFFFFFF
            body.append(f'{indent}ctx->r31 = (gpr)(int32_t)0x{ret:08X}u;')

called = set(re.findall(r'\b(\w+)\(rdram, ctx\);', '\n'.join(body)))
bridges = sorted(c for c in called if c not in defined)
funcs = [f for f in defined if not wanted or f in wanted]

o = []
o.append(f'// Generated by Tools/native_recomp/gen_module.py from N64Recomp output. Do not edit.')
o.append(f'// Module "{name}"')
o.append('#include "Native/NativeModule.h"')
o.append('')
for f in defined:
    o.append(f'RECOMP_FUNC void {f}(uint8_t* rdram, recomp_context* ctx);')
for b in bridges:
    o.append(f'RECOMP_FUNC void {b}(uint8_t* rdram, recomp_context* ctx);')
o.append('')
o += body
o.append('')
o.append('// Guest functions the native code calls but that are not native: run them in Daedalus')
for b in bridges:
    vram = syms[b][0]
    o.append(f'RECOMP_FUNC void {b}(uint8_t* rdram, recomp_context* ctx) {{ native_call_guest(0x{vram:08X}u, rdram, ctx); }}')
o.append('')
o.append('extern const NativeFunction gNativeFuncs_%s[];' % name)
for i, f in enumerate(funcs):
    o.append(f'static uint32_t trampoline_{f}(void) {{ return native_execute(&gNativeFuncs_{name}[{i}]); }}')
o.append('')
o.append(f'const NativeFunction gNativeFuncs_{name}[] = {{')
for f in funcs:
    vram, size = syms[f]
    o.append(f'\t{{ 0x{vram:08X}u, {size // 4}u, 0x{code_hash(vram, size):08X}u, {f}, trampoline_{f}, "{f}" }},')
o.append('};')
o.append('')
o.append(f'// ROM header CRC1/CRC2 of the ROM this was compiled from')
o.append(f'const NativeModule gNativeModule_{name} = {{ "{name}", 0x{rom_crc1:08X}u, 0x{rom_crc2:08X}u, gNativeFuncs_{name}, {len(funcs)}u }};')
o.append('')
o.append('// Registers the module at program start (no central list to edit)')
o.append(f'__attribute__((constructor)) static void register_{name}(void) {{ native_register_module(&gNativeModule_{name}); }}')
open(out, 'w').write('\n'.join(o) + '\n')
print(f'{out}: {len(funcs)} native functions ({", ".join(funcs)}), bridges: {", ".join(bridges) or "none"}')
